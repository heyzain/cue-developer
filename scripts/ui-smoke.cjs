/* Isolated renderer smoke test: never opens websites or uses your Cue data. */
const {app, BrowserWindow} = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'cue-ui-test-'));
app.setPath('userData', profile);
const timer = setTimeout(()=>{ console.error('UI smoke test timed out'); app.exit(1); }, 20000);
app.whenReady().then(async()=>{
  const win = new BrowserWindow({show:false,width:1220,height:900,webPreferences:{contextIsolation:true,sandbox:true}});
  await win.loadFile(path.join(__dirname,'..','index.html'));
  const result = await win.webContents.executeJavaScript(`(async()=>{
    const $=s=>document.querySelector(s);
    const wait=()=>new Promise(r=>setTimeout(r,80));
    const check=(value,message)=>{if(!value)throw Error(message)};
    await wait();
    check($('#content-body .hero'),'Home renders');
    check(getComputedStyle($('.hero')).height==='160px','Accepted compact hero');
    if(document.documentElement.dataset.theme!=='dark')$('#theme-toggle').click();
    check(getComputedStyle(document.body).backgroundColor==='rgb(23, 23, 23)','Neutral charcoal theme');
    check($('#theme-toggle').getAttribute('aria-pressed')==='true','Theme toggle announces its state');
    const mark=$('.quick-tile .site-icon');
    check(mark,'Pinned resources request a website icon');
    check(mark.referrerPolicy==='no-referrer','Icon requests omit the referrer');
    const tile=mark.parentElement;
    const loaded=new Promise((resolve,reject)=>{mark.onload=resolve;mark.onerror=()=>reject(Error('Fixture icon failed'))});
    mark.src='data:image/svg+xml,'+encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32"><circle cx="16" cy="16" r="12" fill="pink"/></svg>');
    await loaded;
    check(tile.classList.contains('has-icon'),'Decoded icon replaces initials');
    check(getComputedStyle(tile.querySelector('.glyph-initials')).visibility==='hidden','Loaded initials are hidden');
    const failed=new Promise(resolve=>{mark.onerror=resolve});
    mark.src='data:image/png;base64,broken';await failed;
    check(!tile.classList.contains('has-icon')&&!tile.querySelector('img'),'Failed image is removed');
    check(getComputedStyle(tile.querySelector('.glyph-initials')).visibility==='visible','Failed icons restore initials');
    $('[data-view="discover"]').click();
    check($('#content-body h1').textContent.includes('All resources'),'All resources navigation');
    $('#add-floating').click();await wait();
    check(getComputedStyle($('#tool-url')).backgroundColor==='rgb(23, 23, 23)','Dark form inputs');
    $('#tool-url').value='example.com/article';$('#tool-url').dispatchEvent(new Event('input'));
    check($('#tool-title').value==='example.com','Automatic URL title');
    check($('#tool-pack').value==='Other','Category is optional');
    $('#tool-purpose').value='Learn React animation';
    $('#tool-form').requestSubmit();await wait();
    check($('#modal-layer').classList.contains('hidden'),'URL-only quick save');
    $('#search-input').value='react animation';$('#search-input').dispatchEvent(new Event('input'));
    check($('#content-body').textContent.includes('example.com'),'Find by purpose');
    $('#sidebar-add').click();$('#category-name').value='Reading';$('#category-form').requestSubmit();await wait();
    check(!!$('[data-view="Reading"]'),'Create category');
    $('[data-rename="Reading"]').click();$('#category-name').value='Articles';$('#category-form').requestSubmit();await wait();
    check(!!$('[data-view="Articles"]')&&!$('[data-view="Reading"]'),'Rename category');
    $('#sidebar-add').click();$('#category-name').value='articles';$('#category-form').requestSubmit();await wait();
    check($('#category-error').textContent.includes('already exists'),'Duplicate category validation');
    $('#category-cancel').click();
    $('#sidebar-add').click();$('#category-name').value='<img src=x onerror=alert(1)>';
    $('#category-form').requestSubmit();await wait();
    check(!$('#pack-nav img'),'Category renders as text');
    return 'Icon loading/fallback, save, search, category creation/rename, validation and escaping passed';
  })()`);
  console.log(result);
  await new Promise(resolve=>{win.webContents.once('did-finish-load',resolve);win.reload();});
  await new Promise(r=>setTimeout(r,250));
  const persisted = await win.webContents.executeJavaScript(`document.querySelector('#pack-nav').textContent.includes('Articles')`);
  if(!persisted)throw Error('Categories did not survive reload');
  const themePersisted = await win.webContents.executeJavaScript(`document.documentElement.dataset.theme==='dark'`);
  if(!themePersisted)throw Error('Theme did not survive reload');
  console.log('Reload persistence passed');
  clearTimeout(timer);win.destroy();app.quit();
}).catch(error=>{console.error(error);clearTimeout(timer);app.exit(1)});
